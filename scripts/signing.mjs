/**
 * Code signing of the Windows executables (#32), opt-in.
 *
 * Unsigned executables trigger SmartScreen on first launch, and leave the
 * auto-updater's integrity resting on the sha512 in latest.yml alone. Signing
 * needs a paid identity, so it stays off until one is configured; nothing
 * changes for a build without it.
 *
 * It uses Azure Trusted Signing through electron-builder's azureSignOptions,
 * which signs the installer and the portable executable alike, and puts the
 * publisher name into app-update.yml so that electron-updater refuses an
 * update not signed by the same publisher. The signing itself runs on Windows,
 * through the TrustedSigning PowerShell module that electron-builder installs.
 *
 * Environment, all required once any is set:
 *
 *   CM_SIGN_PUBLISHER   publisher name exactly as in the certificate
 *   CM_SIGN_ENDPOINT    e.g. https://weu.codesigning.azure.net
 *   CM_SIGN_ACCOUNT     Trusted Signing account name
 *   CM_SIGN_PROFILE     certificate profile name
 *   AZURE_TENANT_ID, AZURE_CLIENT_ID, AZURE_CLIENT_SECRET
 *                       the app registration allowed to sign
 */

const SIGN_KEYS = ['CM_SIGN_PUBLISHER', 'CM_SIGN_ENDPOINT', 'CM_SIGN_ACCOUNT', 'CM_SIGN_PROFILE']
const AZURE_KEYS = ['AZURE_TENANT_ID', 'AZURE_CLIENT_ID', 'AZURE_CLIENT_SECRET']

/**
 * The electron-builder configuration that adds signing to the base one, or
 * null when signing is not configured. A half-configured environment is an
 * error, not a silent unsigned build: whoever set some of the variables meant
 * to sign.
 *
 * @param {Record<string, string | undefined>} env
 * @returns {string | null} YAML for `electron-builder --config`
 */
export function signingConfig(env) {
  const present = SIGN_KEYS.filter((k) => env[k])
  if (present.length === 0) return null

  const missing = [...SIGN_KEYS, ...AZURE_KEYS].filter((k) => !env[k])
  if (missing.length > 0) {
    throw new Error(`Code signing is half configured. Missing: ${missing.join(', ')}`)
  }

  // JSON strings are valid YAML scalars: a publisher name with spaces, quotes
  // or a colon needs no further escaping.
  const q = (v) => JSON.stringify(v)
  return [
    '# Generated by scripts/release.mjs for a signed build (#32). Do not edit.',
    'extends: electron-builder.yml',
    'win:',
    '  azureSignOptions:',
    `    publisherName: ${q(env.CM_SIGN_PUBLISHER)}`,
    `    endpoint: ${q(env.CM_SIGN_ENDPOINT)}`,
    `    codeSigningAccountName: ${q(env.CM_SIGN_ACCOUNT)}`,
    `    certificateProfileName: ${q(env.CM_SIGN_PROFILE)}`,
    ''
  ].join('\n')
}
